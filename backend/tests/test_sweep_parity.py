"""Golden-master parity: indicators/sweep.py must reproduce the TS
computeSweep exactly. The fixture is generated by
frontend/src/lib/indicators/sweepGolden.test.ts; regenerate it there when the
TS math changes."""

import json
from datetime import datetime, timezone
from pathlib import Path

import pytest

from auto_trader.core.models import Candle
from auto_trader.indicators.sweep import SWEEP_OUTPUTS, parse_sweep_config, sweep_series

_DATA = json.loads((Path(__file__).parent / "fixtures" / "sweep_golden.json").read_text())
CANDLES = [
    Candle(datetime.fromtimestamp(t / 1000, tz=timezone.utc), o, h, l, c, v)
    for t, o, h, l, c, v in _DATA["candles"]
]


@pytest.mark.parametrize("case", _DATA["cases"], ids=lambda c: c["name"])
@pytest.mark.parametrize("output", SWEEP_OUTPUTS)
def test_matches_ts(case, output):
    cfg = parse_sweep_config(case["calcParams"], case["extendData"])
    got = sweep_series(cfg, output, CANDLES, 1.0)
    want = case["series"][output]
    assert len(got) == len(want)
    for i, (a, e) in enumerate(zip(got, want)):
        assert a == e, f"{case['name']}.{output}[{i}]: python {a} != ts {e}"
