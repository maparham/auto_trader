def test_edge_cases():
    assert ema_series([], 9) == []
    assert sma_series([1.0, 2.0], 0) == [None, None]
    assert rsi_series([1.0] * 5, 14) == [None] * 5  # n <= period -> all None
    assert atr_series([], 14) == []
